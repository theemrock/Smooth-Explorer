package net.osmand.smooth.routes;

import java.nio.charset.StandardCharsets;

import javax.crypto.Cipher;
import javax.crypto.SecretKey;
import javax.crypto.spec.GCMParameterSpec;

/**
 * AES-GCM seal/open of a short secret. The key is handed in, so the Android side passes an AndroidKeyStore
 * key (never leaves the secure hardware) and unit tests pass a plain software key.
 * Stored form: hex(iv) + ":" + hex(ciphertext with tag). Any problem on open gives null, never an exception.
 */
public final class SecretBox {

	private static final String TRANSFORMATION = "AES/GCM/NoPadding";
	private static final int TAG_BITS = 128;

	private SecretBox() {
	}

	public static String seal(SecretKey key, String plain) throws java.security.GeneralSecurityException {
		Cipher cipher = Cipher.getInstance(TRANSFORMATION);
		cipher.init(Cipher.ENCRYPT_MODE, key); // random IV is generated by the cipher (required by AndroidKeyStore)
		byte[] ct = cipher.doFinal(plain.getBytes(StandardCharsets.UTF_8));
		return hex(cipher.getIV()) + ":" + hex(ct);
	}

	/** @return the secret, or null when the box is empty, damaged, or was sealed with another key */
	public static String open(SecretKey key, String sealed) {
		try {
			if (sealed == null) {
				return null;
			}
			int sep = sealed.indexOf(':');
			if (sep <= 0) {
				return null;
			}
			Cipher cipher = Cipher.getInstance(TRANSFORMATION);
			cipher.init(Cipher.DECRYPT_MODE, key, new GCMParameterSpec(TAG_BITS, unhex(sealed.substring(0, sep))));
			return new String(cipher.doFinal(unhex(sealed.substring(sep + 1))), StandardCharsets.UTF_8);
		} catch (Exception e) {
			return null;
		}
	}

	private static String hex(byte[] bytes) {
		StringBuilder sb = new StringBuilder(bytes.length * 2);
		for (byte b : bytes) {
			sb.append(Character.forDigit((b >> 4) & 0xf, 16)).append(Character.forDigit(b & 0xf, 16));
		}
		return sb.toString();
	}

	private static byte[] unhex(String s) {
		if (s.length() % 2 != 0) {
			throw new IllegalArgumentException("odd length");
		}
		byte[] out = new byte[s.length() / 2];
		for (int i = 0; i < out.length; i++) {
			int hi = Character.digit(s.charAt(2 * i), 16);
			int lo = Character.digit(s.charAt(2 * i + 1), 16);
			if (hi < 0 || lo < 0) {
				throw new IllegalArgumentException("not hex");
			}
			out[i] = (byte) ((hi << 4) | lo);
		}
		return out;
	}
}
